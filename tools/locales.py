def build(root):
    errors = []
    for lang, d in L.items():
        missing = [k for k in KEYS if k not in d]
        extra = [k for k in d if k not in KEYS]
        if missing or extra:
            errors.append(f'{lang}: faltan {missing} sobran {extra}')
            continue
        if len(d['extName']) > 75: errors.append(f'{lang}: extName > 75')
        if len(d['extDescription']) > 132: errors.append(f'{lang}: extDescription {len(d["extDescription"])} > 132')
        if d['extName'] not in d['step1Text']: errors.append(f'{lang}: step1Text no cita el nombre')
        for k in KEYS:  # mismas etiquetas HTML que en español
            if d[k].count('<strong>') != L['es'][k].count('<strong>'):
                errors.append(f'{lang}: {k} tiene distintas etiquetas <strong>')
            if bool(d[k]) != bool(L['es'][k]):
                errors.append(f'{lang}: {k} vacío o sobrante')
        out = {k: {'message': d[k]} for k in KEYS}
        os.makedirs(f'{root}/{lang}', exist_ok=True)
        with open(f'{root}/{lang}/messages.json', 'w', encoding='utf-8') as f:
            f.write(json.dumps(out, ensure_ascii=False, indent=2) + '\n')
    return errors


